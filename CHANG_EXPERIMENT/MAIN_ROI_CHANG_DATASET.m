    'P1','Pz','P2'};

%% ============================================================
% CONTROLLO AUTOMATICO DEI CANALI
% =============================================================

availableChannels = { ...
    'Fp1','Fpz','Fp2','F7','F3','Fz','F4','F8', ...
    'FC5','FC1','FC2','FC6','M1','T7','C3','Cz','C4','T8','M2', ...
    'CP5','CP1','CP2','CP6','P7','P3','Pz','P4','P8', ...
    'POz','O1','O2','EOG', ...
    'AF7','AF3','AF4','AF8', ...
    'F5','F1','F2','F6', ...
    'FC3','FCz','FC4', ...
    'C5','C1','C2','C6', ...
    'CP3','CP4', ...
    'P5','P1','P2','P6', ...
    'PO5','PO3','PO4','PO6', ...
    'FT7','FT8','TP7','TP8', ...
    'PO7','PO8','Oz'};

roiNames = fieldnames(ROI);

for r = 1:numel(roiNames)

    roiName = roiNames{r};
    roiChannels = ROI.(roiName);

    missingChannels = setdiff(roiChannels, availableChannels, ...
                              'stable');

    if ~isempty(missingChannels)
        warning(['ROI "%s": canali non presenti nel chanloc: %s'], ...
            roiName, strjoin(missingChannels, ', '));
    end

    ROI.(roiName) = intersect(roiChannels, availableChannels, ...
                              'stable');
end

%% ============================================================
% VERIFICA FINALE
% =============================================================

disp('ROI create e verificate correttamente.');

for r = 1:numel(roiNames)
    roiName = roiNames{r};

    fprintf('%-18s: %2d canali\n', ...
        roiName, numel(ROI.(roiName)));
end