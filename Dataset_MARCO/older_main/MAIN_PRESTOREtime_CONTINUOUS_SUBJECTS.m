% MAIN_PRESTOREtime_CONTINUOUS_SUBJECTS
clear; close all; clc
rootFolder = 'D:\X-SONANCE\Dataset_MARCO\DATA_SUBJECTS';

subjectDirs = dir(fullfile(rootFolder,'Subj*'));
subjectDirs = subjectDirs([subjectDirs.isdir]);

for s = 4:5
    subjName = subjectDirs(s).name;

    fprintf('\n');
    fprintf('=============================\n');
    fprintf('%s\n',subjName);
    fprintf('=============================\n');

    subjFolder = fullfile(rootFolder,subjName);

    matFiles = dir(fullfile(subjFolder,'*.mat'));

    summaryTable = table();
    currentStart = 1;
    for f = 1:numel(matFiles)

        [~,fileBase,~] = fileparts(matFiles(f).name);

        if contains(fileBase,'relax','IgnoreCase',true)
            continue
        end

        currentFile = fullfile( ...
            subjFolder,...
            matFiles(f).name);

        tmp = load(currentFile);

        y = tmp.y;

        time = y(1,:);
        Fs = round(1/mean(diff(time)));

        fprintf('Sampling rate : %.1f Hz\n',Fs);
        trigger = y(end,:);

        eventOnsets = find(diff([0 trigger~=0])==1);
        eventCodes = trigger(eventOnsets);
        fprintf('First 10 events : ');
        disp(eventCodes(1:min(10,end))')

        fprintf('Last 10 events  : ');
        disp(eventCodes(max(1,end-9):end)')
        durationMin = ...
            (time(end)-time(1))/60;

        fprintf('\n');
        fprintf('%s\n',matFiles(f).name);

        fprintf('Start time : %.3f s\n', ...
            time(1));

        fprintf('End time   : %.3f s\n', ...
            time(end));

        fprintf('Duration   : %.3f min\n', ...
            durationMin);

        fprintf('Events     : %d\n', ...
            numel(eventCodes));

        fprintf('Triggers   : ');
        disp(unique(eventCodes)');
        fprintf('Total trigger count = %d\n', ...
            numel(eventCodes));

        for tr = 1:8
            fprintf('Trigger %d : %d\n', ...
                tr,...
                sum(eventCodes==tr));
        end
        nSamples = size(y,2);
        summaryTable = [summaryTable;
            table( ...
            string(matFiles(f).name), ...
            durationMin, ...
            Fs,...
            nSamples,...
            numel(eventCodes),...
            sum(eventCodes==1),...
            sum(eventCodes==2),...
            sum(eventCodes==3),...
            sum(eventCodes==4),...
            sum(eventCodes==5),...
            sum(eventCodes==6),...
            sum(eventCodes==7),...
            sum(eventCodes==8),...
            'VariableNames',{ ...
            'File',...
            'DurationMin',...
            'Fs',...
            'NSamples',...
            'NEvents',...
            'Trig1',...
            'Trig2',...
            'Trig3',...
            'Trig4',...
            'Trig5',...
            'Trig6',...
            'Trig7',...
            'Trig8'})];
        tokens = regexp(fileBase,...
            '(.*)_(trial\d+)',...
            'tokens');

        if ~isempty(tokens)
            trialInfo(f).trialID = tokens{1}{2};
        end
        trialInfo(f).file = matFiles(f).name;

        trialInfo(f).durationMin = durationMin;

        trialInfo(f).nSamples = nSamples;

        trialInfo(f).nEvents = numel(eventCodes);

        trialInfo(f).triggerCounts = histcounts( ...
            eventCodes,...
            0.5:1:8.5);

        trialInfo(f).firstEvents = ...
            eventCodes(1:min(10,end));

        trialInfo(f).lastEvents = ...
            eventCodes(max(1,end-9):end);


    end

    fprintf('\n');
    disp(summaryTable);

    fprintf('\n');
    fprintf('TOTAL DURATION = %.2f min\n', ...
        sum(summaryTable.DurationMin));

    fprintf('TOTAL EVENTS = %d\n', ...
        sum(summaryTable.NEvents));
    save( ...
        fullfile(subjFolder,...
        sprintf('%s_trialOverview.mat',subjName)),...
        'trialInfo');
    save( ...
        fullfile(subjFolder,...
        sprintf('%s_trialSummary.mat',subjName)),...
        'summaryTable');

    writetable( ...
        summaryTable,...
        fullfile(subjFolder,...
        sprintf('%s_trialSummary.csv',subjName)));
end


