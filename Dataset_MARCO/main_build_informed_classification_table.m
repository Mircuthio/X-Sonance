%% MAIN_BUILD_INFORMED_CLASSIFICATION_TABLE
% Creates a unified table for classification results based on cfgINF.
%
% The script supports either of the following result structures:
%   Results_LOSO.QDA
%   Results_LOSO.LDA
%   Results_LOSO.SVM
%   Results_LOSO.<classifier>
% and/or:
%   Results_TrialWise.<classifier>
%
% The accuracy fields are searched inside the classifier structure:
%   MeanBalancedAccuracy
%   StdBalancedAccuracy
%
% cfgINF fields extracted:
%   useZscore
%   feature_set              -> number of features
%   useERPIndex
%   useERANB
%   useBetaLow
%   analysis_window
%
% If both Results_LOSO and Results_TrialWise are present, LOSO is used
% first and ResultType documents which result group was selected.

clear; clc;

%% Select root folder
rootDir = 'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO\STEP12C_TFRINF_TRIALWISE';

if isequal(rootDir, 0)
    error('No folder selected.');
end

%% Find MAT files recursively
matFiles = dir(fullfile(rootDir, '**', '*.mat'));

% Do not include summaries generated by previous executions.
summaryNames = [ ...
    "ClassificationResults_Summary.mat", ...
    "ClassificationResults_Summary_Unified.mat", ...
    "InferenceClassificationResults_Summary.mat"];

matFiles = matFiles(~ismember(string({matFiles.name}), summaryNames));

if isempty(matFiles)
    error('No input MAT files were found under: %s', rootDir);
end

nFiles = numel(matFiles);
fprintf('Found %d input MAT file(s).\n', nFiles);

%% Preallocate table columns
FileName       = strings(nFiles, 1);
RelativeFolder = strings(nFiles, 1);
FullPath       = strings(nFiles, 1);
ResultType     = strings(nFiles, 1);
Classifier     = strings(nFiles, 1);
Status         = strings(nFiles, 1);

MeanBalancedAccuracy = nan(nFiles, 1);
StdBalancedAccuracy  = nan(nFiles, 1);

UseZscore       = nan(nFiles, 1);
NumberFeatures  = nan(nFiles, 1);
UseERPIndex     = nan(nFiles, 1);
UseERANB        = nan(nFiles, 1);
UseBetaLow      = nan(nFiles, 1);

AnalysisWindowStart = nan(nFiles, 1);
AnalysisWindowEnd   = nan(nFiles, 1);

%% Process each MAT file
for iFile = 1:nFiles
    matPath = fullfile(matFiles(iFile).folder, matFiles(iFile).name);

    FileName(iFile) = string(matFiles(iFile).name);
    FullPath(iFile) = string(matPath);
    RelativeFolder(iFile) = getRelativeFolder( ...
        matFiles(iFile).folder, rootDir);

    try
        % Load into a structure to inspect the available result group.
        S = load(matPath);

        %% Select LOSO or TrialWise
        if isfield(S, 'Results_LOSO') && isstruct(S.Results_LOSO)
            resultGroup = S.Results_LOSO;
            ResultType(iFile) = "LOSO";
        elseif isfield(S, 'Results_TrialWise') && ...
                isstruct(S.Results_TrialWise)
            resultGroup = S.Results_TrialWise;
            ResultType(iFile) = "TrialWise";
        else
            resultGroup = [];
            ResultType(iFile) = "NotFound";
        end

        %% Detect the classifier and extract accuracy fields
        if ~isempty(resultGroup)
            [classifierName, classifierResults] = ...
                findClassifier(resultGroup);

            if ~isempty(classifierResults)
                Classifier(iFile) = classifierName;

                if isfield(classifierResults, 'MeanBalancedAccuracy')
                    MeanBalancedAccuracy(iFile) = scalarValue( ...
                        classifierResults.MeanBalancedAccuracy);
                end

                if isfield(classifierResults, 'StdBalancedAccuracy')
                    StdBalancedAccuracy(iFile) = scalarValue( ...
                        classifierResults.StdBalancedAccuracy);
                end
            else
                Classifier(iFile) = "NotFound";
            end
        else
            Classifier(iFile) = "NotFound";
        end

        %% Extract cfgINF fields
        if isfield(S, 'cfgINF') && isstruct(S.cfgINF)
            cfg = S.cfgINF;

            if isfield(cfg, 'useZscore')
                UseZscore(iFile) = scalarValue(cfg.useZscore);
            end

            if isfield(cfg, 'feature_set')
                NumberFeatures(iFile) = numberOfFeatures(cfg.feature_set);
            end

            if isfield(cfg, 'useERPIndex')
                UseERPIndex(iFile) = scalarValue(cfg.useERPIndex);
            end

            if isfield(cfg, 'useERANB')
                UseERANB(iFile) = scalarValue(cfg.useERANB);
            end

            if isfield(cfg, 'useBetaLow')
                UseBetaLow(iFile) = scalarValue(cfg.useBetaLow);
            end

            if isfield(cfg, 'analysis_window')
                analysisWindow = numericVector(cfg.analysis_window);

                if numel(analysisWindow) >= 1
                    AnalysisWindowStart(iFile) = analysisWindow(1);
                end

                if numel(analysisWindow) >= 2
                    AnalysisWindowEnd(iFile) = analysisWindow(2);
                end
            end
        end

        %% Status
        if ResultType(iFile) == "NotFound"
            Status(iFile) = ...
                "WARNING: Results_LOSO and Results_TrialWise not found";
        elseif Classifier(iFile) == "NotFound"
            Status(iFile) = ...
                "WARNING: classifier result structure not found";
        elseif isnan(MeanBalancedAccuracy(iFile)) && ...
                isnan(StdBalancedAccuracy(iFile))
            Status(iFile) = "WARNING: accuracy fields not found";
        else
            Status(iFile) = "OK";
        end

    catch ME
        ResultType(iFile) = "ERROR";
        Classifier(iFile) = "ERROR";
        Status(iFile) = "ERROR: " + string(ME.message);
        warning('Could not process %s: %s', matPath, ME.message);
    end
end

%% Create table
ResultsTable = table( ...
    FileName, RelativeFolder, FullPath, ...
    ResultType, Classifier, ...
    MeanBalancedAccuracy, StdBalancedAccuracy, ...
    UseZscore, NumberFeatures, UseERPIndex, UseERANB, UseBetaLow, ...
    AnalysisWindowStart, AnalysisWindowEnd, Status);

%% Add combined analysis-window column
ResultsTable.AnalysisWindow = compose('[%.4f %.4f]', ...
    ResultsTable.AnalysisWindowStart, ...
    ResultsTable.AnalysisWindowEnd);

ResultsTable = movevars(ResultsTable, 'AnalysisWindow', ...
    'Before', 'AnalysisWindowStart');

%% Save output
outputMat = fullfile(rootDir, ...
    'InferenceClassificationResults_Summary.mat');
outputCsv = fullfile(rootDir, ...
    'InferenceClassificationResults_Summary.csv');

save(outputMat, 'ResultsTable', 'rootDir');
writetable(ResultsTable, outputCsv);

fprintf('\nSummary table:\n');
disp(ResultsTable);

fprintf('\nSaved MAT summary:\n%s\n', outputMat);
fprintf('Saved CSV summary:\n%s\n', outputCsv);

%% Local functions
function [classifierName, classifierResults] = findClassifier(resultGroup)
    % Finds the first classifier structure containing an accuracy field.
    classifierName = "";
    classifierResults = [];

    if ~isstruct(resultGroup)
        return;
    end

    fields = fieldnames(resultGroup);

    for iField = 1:numel(fields)
        candidateName = fields{iField};
        candidate = resultGroup.(candidateName);

        if isstruct(candidate) && ...
                (isfield(candidate, 'MeanBalancedAccuracy') || ...
                 isfield(candidate, 'StdBalancedAccuracy'))
            classifierName = string(candidateName);
            classifierResults = candidate;
            return;
        end
    end
end

function value = scalarValue(x)
    if iscell(x)
        if isempty(x)
            value = NaN;
            return;
        end
        x = x{1};
    end

    if isstring(x) || ischar(x)
        x = str2double(string(x));
    end

    if isnumeric(x) || islogical(x)
        x = x(:);
        if isempty(x)
            value = NaN;
        else
            value = double(x(1));
        end
    else
        value = NaN;
    end
end

function n = numberOfFeatures(x)
    % Counts the number of selected features.
    % For a 16x1 cell array, this returns 16.
    if iscell(x) || isstring(x) || ischar(x) || ...
            isnumeric(x) || islogical(x) || iscategorical(x)
        n = numel(x);
    else
        n = NaN;
    end
end

function value = numericVector(x)
    if iscell(x)
        if isempty(x)
            value = [];
            return;
        end
        x = x{1};
    end

    if isnumeric(x) || islogical(x)
        value = double(x(:)).';
    elseif isstring(x) || ischar(x)
        value = str2num(char(x)); %#ok<ST2NM>
    else
        value = [];
    end
end

function relativeFolder = getRelativeFolder(currentFolder, rootFolder)
    currentFolder = string(currentFolder);
    rootFolder = string(rootFolder);

    if currentFolder == rootFolder
        relativeFolder = ".";
        return;
    end

    prefix = rootFolder + filesep;

    if startsWith(currentFolder, prefix)
        relativeFolder = extractAfter(currentFolder, strlength(prefix));
    else
        relativeFolder = currentFolder;
    end
end