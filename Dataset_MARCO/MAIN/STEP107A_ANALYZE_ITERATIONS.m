%% =========================================================================
% STEP107A_ANALYZE_ITERATIONS
%
% ANALISI ITERATION-BY-ITERATION
%
% DATASETS:
%   FULL_264
%   ERP_ONLY_156
%   BANDPOWER_ONLY_108
%   REDUCED_29
%
%% =========================================================================
clear
close all
clc

%% =========================================================================
% PATHS
%% =========================================================================
projectRoot = ...
    'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO';

indir = fullfile( ...
    projectRoot,...
    'STEP107_GENERAL_CLASSIFIER_TRIALWISE');

%% =========================================================================
% FILES
%% =========================================================================
DatasetFiles = { ...
    'FULL_264_TRIALWISE.mat'
    'ERP_ONLY_156_TRIALWISE.mat'
    'BANDPOWER_ONLY_108_TRIALWISE.mat'
    'REDUCED_29_TRIALWISE.mat'};

Classifiers = { ...
    'QDA'
    'KNN'
    'NB'};

%% =========================================================================
% ANALYSIS
%% =========================================================================
SummaryTable = table();

for iDataset = 1:numel(DatasetFiles)

    fprintf('\n');
    fprintf('====================================================\n');
    fprintf('%s\n',DatasetFiles{iDataset});
    fprintf('====================================================\n');

    S = load( ...
        fullfile( ...
        indir,...
        DatasetFiles{iDataset}));

    Results_TrialWise = ...
        S.Results_TrialWise;

    for iClf = 1:numel(Classifiers)

        classifierName = ...
            Classifiers{iClf};

        fprintf('\n');
        fprintf('%s\n',classifierName);

        Iter = ...
            Results_TrialWise.(classifierName).Iter;

        for iIter = 1:numel(Iter)

            ACC = ...
                Iter(iIter).TestMetrics.ACC;

            BA = ...
                Iter(iIter).TestMetrics.BA;

            F1 = ...
                Iter(iIter).TestMetrics.F1;

            MCC = ...
                Iter(iIter).TestMetrics.MCC;

            fprintf( ...
                'ITER %02d  ACC=%.3f  BA=%.3f  F1=%.3f  MCC=%.3f\n',...
                iIter,...
                ACC,...
                BA,...
                F1,...
                MCC);

            newRow = table( ...
                string(Results_TrialWise.DatasetName), ...
                string(classifierName), ...
                iIter,...
                ACC,...
                BA,...
                F1,...
                MCC,...
                'VariableNames',{ ...
                'Dataset',...
                'Classifier',...
                'Iteration',...
                'ACC',...
                'BA',...
                'F1',...
                'MCC'});

            SummaryTable = ...
                [SummaryTable ; newRow];

        end
    end
end

%% =========================================================================
% SAVE
%% =========================================================================
writetable( ...
    SummaryTable,...
    fullfile( ...
    indir,...
    'STEP107A_ITERATION_RESULTS.xlsx'));

save( ...
    fullfile( ...
    indir,...
    'STEP107A_ITERATION_RESULTS.mat'),...
    'SummaryTable');

%% =========================================================================
% SUMMARY BY DATASET
%% =========================================================================
fprintf('\n');
fprintf('====================================================\n');
fprintf('DATASET SUMMARY\n');
fprintf('====================================================\n');

Datasets = ...
    unique(SummaryTable.Dataset);

for iD = 1:numel(Datasets)

    fprintf('\n');
    fprintf('%s\n',Datasets(iD));

    for iClf = 1:numel(Classifiers)

        classifierName = ...
            Classifiers{iClf};

        idx = ...
            SummaryTable.Dataset == Datasets(iD) & ...
            SummaryTable.Classifier == classifierName;

        if ~any(idx)
            continue
        end

        fprintf('%s\n',classifierName);

        fprintf('Mean ACC : %.3f +/- %.3f\n', ...
            mean(SummaryTable.ACC(idx)),...
            std(SummaryTable.ACC(idx)));

        fprintf('Mean BA  : %.3f +/- %.3f\n', ...
            mean(SummaryTable.BA(idx)),...
            std(SummaryTable.BA(idx)));

        fprintf('Mean F1  : %.3f +/- %.3f\n', ...
            mean(SummaryTable.F1(idx)),...
            std(SummaryTable.F1(idx)));

        fprintf('Mean MCC : %.3f +/- %.3f\n', ...
            mean(SummaryTable.MCC(idx)),...
            std(SummaryTable.MCC(idx)));

        fprintf('\n');
    end
end

