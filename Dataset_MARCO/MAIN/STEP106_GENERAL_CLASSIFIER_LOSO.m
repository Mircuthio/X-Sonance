%% =========================================================================
% STEP106_GENERAL_CLASSIFIER_LOSO
%
% CLASSIFICATION BENCHMARK
%
% DATASETS
%
%   FULL_264
%   ERP_ONLY_156
%   BANDPOWER_ONLY_108
%   REDUCED_29
%
%
% PIPELINE
%
%   LOAD DATASET
%       ↓
%   LOSO SPLIT
%       ↓
%   TRAIN Z-SCORE
%       ↓
%   APPLY TO TEST
%       ↓
%   CONVERT FEATURES TO EEG STRUCT
%       ↓
%   run_classifier_fold
%       ↓
%   mdlPredict
%       ↓
%   ACC / BA / F1 / MCC
%
%% =========================================================================
clear
close all
clc

%% =========================================================================
% PATHS
%% =========================================================================
projectRoot = ...
    'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO';

indir = fullfile( ...
    projectRoot,...
    'STEP105_FINAL_DATASETS');

outdir = fullfile( ...
    projectRoot,...
    'STEP106_GENERAL_CLASSIFIER_LOSO','noZscore');

if ~exist(outdir,'dir')
    mkdir(outdir);
end

%% =========================================================================
% CONFIG
%% =========================================================================
cfgCLS = struct();
cfgCLS.randomSeed = 10;

rng(cfgCLS.randomSeed)

cfgCLS.zscore = false;

cfgCLS.classifiers = { ...
    % 'SVC',...
    'QDA',...
    'KNN'};
    % ,...
    % 'NB'};

%% =========================================================================
% DATASETS
%% =========================================================================
DatasetInfo = {
    'DATASET_FULL_264.mat'           'FULL_264'
    'DATASET_ERP_ONLY_156.mat'       'ERP_ONLY_156'
    'DATASET_BANDPOWER_ONLY_108.mat' 'BANDPOWER_ONLY_108'
    'DATASET_REDUCED_29.mat'         'REDUCED_29'
    };

%% =========================================================================
% LOOP DATASETS
%% =========================================================================
for iDataset = 1:size(DatasetInfo,1)

    fprintf('\n');
    fprintf('=================================================\n');
    fprintf('DATASET %d/%d\n', ...
        iDataset,...
        size(DatasetInfo,1));
    fprintf('=================================================\n');

    datasetFile = DatasetInfo{iDataset,1};
    variableName = DatasetInfo{iDataset,2};

    S = load(fullfile(indir,datasetFile));
    Dataset = S.(variableName);
    DatasetName = variableName;

    fprintf('Dataset : %s\n',DatasetName);

    assert(size(Dataset.X,1) == length(Dataset.Y))
    assert(size(Dataset.X,1) == length(Dataset.SubjectID))

    %% =====================================================================
    % SUMMARY
    %% =====================================================================
    fprintf('Trials   : %d\n', ...
        size(Dataset.X,1));
    fprintf('Features : %d\n', ...
        size(Dataset.X,2));

    %% =====================================================================
    % SUBJECTS
    %% =====================================================================
    subjectIDs = unique(Dataset.SubjectID);
    nSubjects = numel(subjectIDs);

    fprintf('\n');
    fprintf('Subjects found:\n');

    for i = 1:numel(subjectIDs)
        fprintf('%s\n',subjectIDs{i});
    end

    fprintf('\n');
    fprintf('Total subjects: %d\n', ...
        numel(subjectIDs));
    fprintf('Subjects : %d\n', ...
        nSubjects);

    %% =====================================================================
    % LOSO RESULTS
    %% =====================================================================
    Results_LOSO = struct();
    Results_LOSO.DatasetName = DatasetName;
    FoldTemplate = struct( ...
        'DatasetName',   DatasetName, ...
        'classifier',    '', ...
        'testSubject',   '', ...
        'nTrainTrials',  0, ...
        'nTestTrials',   0, ...
        'nFeatures',     0, ...
        'ModelType',     '', ...
        'Model',        struct(), ...
        'TrainMetrics',  struct(), ...
        'TestMetrics',   struct(), ...
        'Ytrain_true',   [], ...
        'Ytrain_pred',   [], ...
        'Ytest_true',    [], ...    
        'Ytest_pred',    [], ...
        'resTrain',      [], ...
        'resTest',       []);
    %% =====================================================================
    % CLASSIFIERS
    %% =====================================================================
    tabulate(Dataset.Y)

    for iClf = 1:numel(cfgCLS.classifiers)

        classifierName = ...
            cfgCLS.classifiers{iClf};
        
        Results_LOSO.(classifierName).Fold = ...
            repmat(FoldTemplate,1,nSubjects);

        fprintf('\n');
        fprintf('------------------------------------------\n');
        fprintf('CLASSIFIER : %s\n', ...
            classifierName);
        fprintf('------------------------------------------\n');

        %% ================================================================
        % LOSO
        %% ================================================================
        for iSub = 1:nSubjects

            testSubject = subjectIDs{iSub};

            fprintf('Test Subject : %s\n', ...
                testSubject);
            fprintf('\n');
            fprintf('LOSO Fold %d/%d\n', ...
                iSub,nSubjects);

            %% ------------------------------------------------------------
            % SPLIT
            %% ------------------------------------------------------------
            idxTest = strcmp( ...
                Dataset.SubjectID,...
                testSubject);

            idxTrain = ...
                ~idxTest;

            Xtrain = ...
                Dataset.X(idxTrain,:);
            Ytrain = ...
                Dataset.Y(idxTrain);

            Xtest = ...
                Dataset.X(idxTest,:);
            Ytest = ...
                Dataset.Y(idxTest);

            %% ------------------------------------------------------------
            % ZSCORE TRAIN ONLY
            %% ------------------------------------------------------------
            if cfgCLS.zscore
                mu = mean(Xtrain,1);
                sigma = std(Xtrain,[],1);
                sigma(sigma==0) = 1;

                Xtrain = ...
                    (Xtrain - mu) ./ sigma;

                Xtest = ...
                    (Xtest - mu) ./ sigma;
            end
            %% ------------------------------------------------------------
            % MASTERDATASET FEATURES
            %% ------------------------------------------------------------
            Features = ...
                run_masterdataset_features( ...
                Xtrain,...
                Ytrain,...
                Xtest,...
                Ytest);

            %% ------------------------------------------------------------
            % CLASSIFIER
            %% ------------------------------------------------------------
            parClassifier = struct();

            parClassifier.InField = ...
                Features.SignalField;

            [TrainEEG,...
                TestEEG,...
                outClassifier,...
                PredField,...
                ProbField] = ...
                run_classifier_fold( ...
                Features.TrainEEG,...
                Features.TestEEG,...
                classifierName,...
                parClassifier);

            %% ------------------------------------------------------------
            % PREDICTION
            %% ------------------------------------------------------------
            parPredict = ...
                mdlPredictParams();

            parPredict.InField = ...
                Features.SignalField;

            parPredict.OutField = ...
                PredField;
            parPredict.ProbField = ...
                ProbField;
            parPredict.mdl = ...
                outClassifier.mdl;

            [TrainEEG,resTrain] = ...
                mdlPredict( ...
                TrainEEG,...
                parPredict);

            [TestEEG,resTest] = ...
                mdlPredict( ...
                TestEEG,...
                parPredict);

            %% ------------------------------------------------------------
            % LABELS
            %% ------------------------------------------------------------
            Ytrain_true = ...
                [TrainEEG.trialType]';

            Ytrain_pred = ...
                [TrainEEG.(PredField)]';

            Ytest_true = ...
                [TestEEG.trialType]';

            Ytest_pred = ...
                [TestEEG.(PredField)]';

            %% ------------------------------------------------------------
            % METRICS
            %% ------------------------------------------------------------
            TrainMetrics = ...
                compute_classification_metrics( ...
                Ytrain_true,...
                Ytrain_pred);

            TestMetrics = ...
                compute_classification_metrics( ...
                Ytest_true,...
                Ytest_pred);

            %% ------------------------------------------------------------
            % STORE RESULTS
            %% ------------------------------------------------------------
            FoldResult = FoldTemplate;

            FoldResult.DatasetName = ...
                DatasetName;
            FoldResult.classifier = ...
                classifierName;
            FoldResult.testSubject = ...
                testSubject;
            FoldResult.nTrainTrials = ...
                numel(Ytrain_true);
            FoldResult.nTestTrials = ...
                numel(Ytest_true);
            FoldResult.nFeatures = ...
                Features.nFeatures;
            FoldResult.Model = ...
                outClassifier;
            FoldResult.ModelType = ...
                classifierName;

            FoldResult.TrainMetrics = ...
                TrainMetrics;
            FoldResult.TestMetrics = ...
                TestMetrics;

            FoldResult.Ytrain_true = ...
                Ytrain_true;
            FoldResult.Ytrain_pred = ...
                Ytrain_pred;

            FoldResult.Ytest_true = ...
                Ytest_true;
            FoldResult.Ytest_pred = ...
                Ytest_pred;

            FoldResult.resTrain = ...
                resTrain;
            FoldResult.resTest = ...
                resTest;

            Results_LOSO.(classifierName).Fold(iSub) = ...
                FoldResult;
        end

        %% ================================================================
        % GLOBAL PREDICTIONS
        %% ================================================================
        Ytrue_global = [];
        Ypred_global = [];

        for iFold = 1:numel(Results_LOSO.(classifierName).Fold)

            Ytrue_global = [ ...
                Ytrue_global;
                Results_LOSO.(classifierName).Fold(iFold).Ytest_true];

            Ypred_global = [ ...
                Ypred_global;
                Results_LOSO.(classifierName).Fold(iFold).Ytest_pred];
        end

        Results_LOSO.(classifierName).Ytrue_global = ...
            Ytrue_global;
        Results_LOSO.(classifierName).Ypred_global = ...
            Ypred_global;

        Results_LOSO.(classifierName).ConfusionMatrix = ...
            confusionmat(Ytrue_global,Ypred_global);

        %% ================================================================
        % SUMMARY
        %% ================================================================
        allACC = ...
            arrayfun( ...
            @(x) x.TestMetrics.ACC,...
            Results_LOSO.(classifierName).Fold);

        allBA = ...
            arrayfun( ...
            @(x) x.TestMetrics.BA,...
            Results_LOSO.(classifierName).Fold);

        allF1 = ...
            arrayfun( ...
            @(x) x.TestMetrics.F1,...
            Results_LOSO.(classifierName).Fold);

        allMCC = ...
            arrayfun( ...
            @(x) x.TestMetrics.MCC,...
            Results_LOSO.(classifierName).Fold);

        Results_LOSO.(classifierName).MeanAccuracy = ...
            mean(allACC);
        Results_LOSO.(classifierName).StdAccuracy = ...
            std(allACC);

        Results_LOSO.(classifierName).MeanBalancedAccuracy = ...
            mean(allBA);
        Results_LOSO.(classifierName).StdBalancedAccuracy = ...
            std(allBA);

        Results_LOSO.(classifierName).MeanF1 = ...
            mean(allF1,'omitnan');
        Results_LOSO.(classifierName).StdF1 = ...
            std(allF1,'omitnan');

        Results_LOSO.(classifierName).MeanMCC = ...
            mean(allMCC,'omitnan');
        Results_LOSO.(classifierName).StdMCC = ...
            std(allMCC,'omitnan');

        Results_LOSO.(classifierName).cfg = ...
            cfgCLS;
        Results_LOSO.(classifierName).SignalField = ...
            Features.SignalField;
        fprintf('\n');
        fprintf('%s RESULTS\n', ...
            classifierName);
        fprintf('ACC : %.2f %%\n', ...
            100 * ...
            Results_LOSO.(classifierName).MeanAccuracy);
        fprintf('BA  : %.2f %%\n', ...
            100 * ...
            Results_LOSO.(classifierName).MeanBalancedAccuracy);
        fprintf('F1  : %.4f\n', ...
            Results_LOSO.(classifierName).MeanF1);
        fprintf('MCC : %.4f\n', ...
            Results_LOSO.(classifierName).MeanMCC);
    end

    %% =====================================================================
    % SAVE
    %% =====================================================================
    
    save( ...
        fullfile( ...
        outdir,...
        sprintf('%s_LOSO.mat', ...
        DatasetName)),...
        'Results_LOSO',...
        'cfgCLS',...
        'Dataset',...
        '-v7.3');

    fprintf('\n');
    fprintf('Saved : %s\n', ...
        DatasetName);
end

