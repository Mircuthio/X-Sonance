%% ============================================================
% MAIN_DATASET_MARCO_ERP_STEP5
%
% Statistical evaluation of ERP components
%
% Input:
%   ERP_STEP3_RESULTS.mat
%
% Output:
%   ERP_Window_Statistics.mat
%   ERP_Window_Statistics.csv
%
%
% Columns:
%
% ROI
% Window Start
% Window End
% Mean Condition 1
% Mean Condition 2
% Mean Difference
% t statistic
% p value
%
%
% =========================================================================
comparisonName = 'Consonance';

erpDir = fullfile(...
'D:\X-SONANCE\Dataset_MARCO\DATA_SUBJECTS\All_trials\EPOCH_DATA\',comparisonName);

erpFile = ...
fullfile(erpDir,'ERP_STEP3_RESULTS.mat');

assert(exist(erpFile,'file')==2,...
    'STEP3 result file not found');

load(erpFile,...
    'limo_input',...
    'cfg');


switch comparisonName
    case 'Consonance'
        cfg.conditions = { ...
            'Consonant',...
            'Dissonant'};
    case 'Difference'
        cfg.conditions = { ...
            'ConsonantGOAL',...
            'DissonantNoGOAL'};
    case 'Goal'
        cfg.conditions = { ...
            'ConsonantGOAL',...
            'DissonantGOAL'};
    case 'NoGoal'
        cfg.conditions = { ...
            'ConsonantNoGOAL',...
            'DissonantNoGOAL'};

    case 'Control'
        cfg.conditions = { ...
            'ControlGOAL',...
            'ControlNoGOAL'};
    case 'All'
        cfg.conditions = { ...
            'ConsonantGOAL',...
            'DissonantGOAL',...
            'ControlGOAL',...
            'ConsonantNoGOAL',...
            'DissonantNoGOAL',...
            'ControlNoGOAL',...
            'Consonant',...
            'Dissonant'};
end

cfgStats = struct();

cfgStats.erpWindows = struct();

cfgStats.erpWindows.ERAN       = [0.18 0.23];

cfgStats.erpWindows.ERAN_RIGHT = [0.18 0.23];

cfgStats.erpWindows.MMN        = [0.10 0.20];

cfgStats.erpWindows.N5         = [0.45 0.55];

cfg.statROIs = { ...
    'Generic',...
    'ERAN',...
    'ERAN_CORE',...
    'ERAN_RIGHT',...
    'MMN',...
    'N5'};
cfgStats.conditions = cfg.conditions;

fprintf('\n');
fprintf('=====================================\n');
fprintf('STEP5 ROI WINDOW STATISTICS\n');
fprintf('=====================================\n');
ResultsStats = table();

for r = 1:numel(cfg.statROIs)

    roiName = cfg.statROIs{r};

    if ~isfield(limo_input,roiName)
        continue
    end

    cfgCurr = struct();

    cfgCurr.conditions = cfg.conditions;
    cfgCurr.window = cfg.erpWindows.(roiName);

    S = compute_roi_window_statistics( ...
        limo_input.(roiName),...
        cfgCurr);

    newRow = table( ...
        string(roiName),...
        cfgCurr.window(1),...
        cfgCurr.window(2),...
        S.meanA,...
        S.meanB,...
        S.diffMean,...
        S.diffSD,...
        S.t,...
        S.df,...
        S.p,...
        'VariableNames',{ ...
        'ROI',...
        'WinStart',...
        'WinEnd',...
        'MeanCond1',...
        'MeanCond2',...
        'MeanDiff',...
        'SdDiff',...
        't',...
        'df',...
        'p'});

    ResultsStats = [ResultsStats; newRow];

end
ResultsStats = sortrows( ...
    ResultsStats,...
    'p');

disp(ResultsStats)

save( ...
    fullfile(outdir,...
    'ERP_Window_Statistics.mat'),...
    'ResultsStats');

writetable( ...
    ResultsStats,...
    fullfile(outdir,...
    'ERP_Window_Statistics.csv'));
