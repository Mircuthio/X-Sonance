    size(FeatureDataset.X,2));
fprintf('NaN values : %d\n', ...
    sum(isnan(FeatureDataset.X(:))));

fprintf('Inf values : %d\n', ...
    sum(isinf(FeatureDataset.X(:))));
fprintf('Labels   : %d\n', ...
    numel(FeatureDataset.Y));

