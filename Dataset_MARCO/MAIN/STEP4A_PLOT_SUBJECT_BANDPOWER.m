%% ============================================================
% STEP4A_PLOT_SUBJECT_BANDPOWER
%% ============================================================

% clear
% close all
% clc
origState = get(0,'DefaultFigureVisible');
set(0,'DefaultFigureVisible','off');
set(groot,...
    'defaultTextInterpreter','tex');
set(groot,...
    'defaultAxesTickLabelInterpreter','tex');
set(groot,...
    'defaultLegendInterpreter','tex');
% addpath('C:\Users\mirco\Desktop\eeglab2026.1.0')
% eeglab nogui
%% ============================================================
% LOAD RESULTS
%% ============================================================

% load( ...
%     'BANDPOWER_STEP4A_RESULTS.mat',...
%     'BandPower_Subj');

subjNames = fieldnames(BandPower_Subj);

%% ============================================================
% SETTINGS
%% ============================================================
% MAIN_ROI
roiNames = { ...
    'ERAN_CORE',...
    'MMN',...
    'FrontoCentral',...
    'N5_CENTRAL'};

bandNames = { ...
    'Delta',...
    'Theta',...
    'Alpha',...
    'BetaLow',...
    'BetaHigh',...
    'GammaLow',...
    'GammaHigh'};

outdir = 'SubjectPlots';

if ~exist(outdir,'dir')
    mkdir(outdir);
end
%% ============================================================
% LOOP SUBJECTS
%% ============================================================

for iSub = 1:numel(subjNames)

    subjID = subjNames{iSub};

    fprintf('\nSubject: %s\n',subjID);

    for r = 1:numel(roiNames)

        roiName = roiNames{r};

        roiDir = ...
            fullfile(outdir,roiName);

        if ~exist(roiDir,'dir')
            mkdir(roiDir);
        end

        for b = 1:numel(bandNames)

            bandName = bandNames{b};

            try

                bp = ...
                    BandPower_Subj.(subjID).(roiName).(bandName);

                %% =====================================================
                % BOTH CONDITIONS
                %% =====================================================

                figBoth = figure( ...
                    'Color','w',...
                    'Position',[100 100 900 500]);

                hold on

                plot( ...
                    bp.time,...
                    bp.Consonant.power,...
                    'b',...
                    'LineWidth',2);

                plot( ...
                    bp.time,...
                    bp.Dissonant.power,...
                    'r',...
                    'LineWidth',2);

                xline(0,'k:');

                legend( ...
                    {'Consonant',...
                     'Dissonant'},...
                     'Location','best');

                title(sprintf( ...
                    '%s | %s | %s',...
                    subjID,...
                    roiName,...
                    bandName),...
                    'Interpreter','none');

                xlabel('Time (s)');
                ylabel('Band Power');

                grid on

                saveas( ...
                    figBoth,...
                    fullfile( ...
                    roiDir,...
                    sprintf( ...
                    '%s_%s_%s_BOTH.png',...
                    subjID,...
                    roiName,...
                    bandName)));

                close(figBoth)

                %% =====================================================
                % DIFFERENCE
                %% =====================================================

                figDiff = figure( ...
                    'Color','w',...
                    'Position',[100 100 900 500]);

                hold on

                plot( ...
                    bp.time,...
                    bp.Difference.power,...
                    'k',...
                    'LineWidth',2);

                yline(0,'k:');
                xline(0,'k:');

                title(sprintf( ...
                    '%s | %s | %s | Difference',...
                    subjID,...
                    roiName,...
                    bandName),...
                    'Interpreter','none');

                xlabel('Time (s)');
                ylabel('Difference Power');

                grid on

                saveas( ...
                    figDiff,...
                    fullfile( ...
                    roiDir,...
                    sprintf( ...
                    '%s_%s_%s_DIFF.png',...
                    subjID,...
                    roiName,...
                    bandName)));

                close(figDiff)

                fprintf('   %s | %s OK\n', ...
                    roiName,...
                    bandName);

            catch ME

                fprintf( ...
                    'Missing: %s | %s | %s\n',...
                    subjID,...
                    roiName,...
                    bandName);

                fprintf('%s\n',ME.message);

            end

        end

    end

end

set(0,'DefaultFigureVisible',origState);

fprintf('\n');
fprintf('================================\n');
fprintf('STEP4A PLOT SUBJECT BANDPOWER COMPLETED\n');
fprintf('================================\n');

