clear
close all
clc

origState = get(0, 'DefaultFigureVisible');
set(0, 'DefaultFigureVisible', 'off');

set(groot,...
    'defaultTextInterpreter','tex');
set(groot,...
    'defaultAxesTickLabelInterpreter','tex');
set(groot,...
    'defaultLegendInterpreter','tex');
% addpath('C:\Users\mirco\Desktop\eeglab2026.1.0')
% eeglab nogui
%% =========================================================================
% PATHS
%% =========================================================================

projectRoot = ...
    'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO';

inputFile = fullfile( ...
    projectRoot,...
    'STEP4B_TFR_MORLET',...
    'STEP4C_TFR_SUBJECT_LINEAR',...
    'STEP4C_TFR_SUBJECT_LINEAR.mat');

outputRoot = fullfile( ...
    projectRoot,...
    'STEP4B_TFR_MORLET',...
    'STEP4D_TFR_SUBJECT_HEATMAPS_AND_LATENCY');

if ~exist(outputRoot,'dir')
    mkdir(outputRoot);
end

figDir = fullfile(outputRoot,'Figures');

if ~exist(figDir,'dir')
    mkdir(figDir);
end

%% =========================================================================
% LOAD
%% =========================================================================

load(inputFile,'TFR_Subj','cfgTFR');

subjectNames = fieldnames(TFR_Subj);

nSubjects = numel(subjectNames);

roiNames = fieldnames(cfgTFR.rois);

bandNames = fieldnames(cfgTFR.freqBands);

%% =========================================================================
% TABLE INITIALIZATION
%% =========================================================================

LatencyTable = table();

%% =========================================================================
% MAIN LOOP
%% =========================================================================

for r = 1:numel(roiNames)

    roiName = roiNames{r};

    fprintf('\nROI : %s\n',roiName);

    for b = 1:numel(bandNames)

        bandName = bandNames{b};

        fprintf('Band : %s\n',bandName);

        heatmapData = [];

        negLat = nan(nSubjects,1);
        posLat = nan(nSubjects,1);
        absLat = nan(nSubjects,1);

        negAmp = nan(nSubjects,1);
        posAmp = nan(nSubjects,1);
        absAmp = nan(nSubjects,1);

        aucVal = nan(nSubjects,1);
        meanVal = nan(nSubjects,1);
        stdVal = nan(nSubjects,1);

        timeVector = [];

        %% ================================================================
        % SUBJECT LOOP
        %% ================================================================

        for s = 1:nSubjects

            subjID = subjectNames{s};

            if ~isfield(TFR_Subj.(subjID),roiName)
                continue
            end

            roiData = TFR_Subj.(subjID).(roiName);

            freq = roiData.freq(:);

            bandRange = cfgTFR.freqBands.(bandName);

            idxBand = ...
                freq >= bandRange(1) & ...
                freq <= bandRange(2);

            if ~any(idxBand)
                continue
            end

            conTC = mean( ...
                roiData.Consonant.power(idxBand,:), ...
                1,'omitnan');

            disTC = mean( ...
                roiData.Dissonant.power(idxBand,:), ...
                1,'omitnan');

            diffTC = conTC - disTC;

            timeVector = roiData.time(:)';

            heatmapData(s,:) = diffTC;

            %% ------------------------------------------------------------
            % PEAKS IN ANALYSIS WINDOW
            %% ------------------------------------------------------------
            idxWin = ...
                timeVector >= 0 & ...
                timeVector <= 0.8;

            waveWin = diffTC(idxWin);
            timeWin = timeVector(idxWin);

            %% ------------------------------------------------------------
            % NEGATIVE PEAK
            %% ------------------------------------------------------------
            [negAmp(s),idxNeg] = min(waveWin);
            negLat(s) = timeWin(idxNeg);

            %% ------------------------------------------------------------
            % POSITIVE PEAK
            %% ------------------------------------------------------------
            [posAmp(s),idxPos] = max(waveWin);
            posLat(s) = timeWin(idxPos);

            %% ------------------------------------------------------------
            % ABSOLUTE PEAK
            %% ------------------------------------------------------------
            [~,idxAbs] = max(abs(waveWin));
            absLat(s) = timeWin(idxAbs);
            absAmp(s) = waveWin(idxAbs);

            %% ------------------------------------------------------------
            % GLOBAL METRICS
            %% ------------------------------------------------------------
            meanVal(s) = mean(waveWin,'omitnan');
            stdVal(s)  = std(waveWin,'omitnan');

            aucVal(s) = trapz( ...
                timeWin,...
                abs(waveWin));

            %% ------------------------------------------------------------
            % TABLE ROW
            %% ------------------------------------------------------------

            newRow = table( ...
                {roiName}, ...
                {bandName}, ...
                {subjID}, ...
                negAmp(s), ...
                negLat(s), ...
                posAmp(s), ...
                posLat(s), ...
                absAmp(s), ...
                absLat(s), ...
                meanVal(s), ...
                stdVal(s), ...
                aucVal(s), ...
                'VariableNames',{ ...
                'ROI', ...
                'Band', ...
                'Subject', ...
                'NegAmp', ...
                'NegLatency', ...
                'PosAmp', ...
                'PosLatency', ...
                'AbsAmp', ...
                'AbsLatency', ...
                'MeanDifference', ...
                'StdDifference', ...
                'AUCAbsDifference'});

            LatencyTable = ...
                [LatencyTable ; newRow];

        end

        %% ================================================================
        % HEATMAP SIMPLE
        %% ================================================================

        fig = figure( ...
            'Color','w',...
            'Position',[100 100 1200 650]);

        imagesc( ...
            timeVector*1000,...
            1:nSubjects,...
            heatmapData);

        axis xy

        colorbar

        xlabel('Time (ms)')
        ylabel('Subject')

        title(sprintf( ...
            '%s | %s | Difference', ...
            roiName, ...
            bandName));

        saveas(fig,...
            fullfile(figDir,...
            sprintf( ...
            '%s_%s_HEATMAP.png',...
            roiName,...
            bandName)));

        close(fig)

        %% ================================================================
        % HEATMAP WITH PEAKS
        %% ================================================================

        fig = figure( ...
            'Color','w',...
            'Position',[100 100 1200 650]);

        imagesc( ...
            timeVector*1000,...
            1:nSubjects,...
            heatmapData);

        axis xy

        hold on

        scatter( ...
            negLat*1000,...
            1:nSubjects,...
            60,...
            'wo',...
            'filled');

        scatter( ...
            posLat*1000,...
            1:nSubjects,...
            60,...
            'gs',...
            'filled');

        scatter( ...
            absLat*1000,...
            1:nSubjects,...
            80,...
            'r*');

        colorbar

        xlabel('Time (ms)')
        ylabel('Subject')

        title(sprintf( ...
            '%s | %s | Peaks', ...
            roiName, ...
            bandName));

        legend( ...
            'Negative Peak',...
            'Positive Peak',...
            'Absolute Peak',...
            'Location','best');

        saveas(fig,...
            fullfile(figDir,...
            sprintf( ...
            '%s_%s_HEATMAP_PEAKS.png',...
            roiName,...
            bandName)));

        close(fig)

        %% ================================================================
        % HEATMAP SORTED BY ABSOLUTE LATENCY
        %% ================================================================

        [~,ord] = sort(absLat);

        fig = figure( ...
            'Color','w',...
            'Position',[100 100 1200 650]);

        imagesc( ...
            timeVector*1000,...
            1:nSubjects,...
            heatmapData(ord,:));

        axis xy

        colorbar

        xlabel('Time (ms)')
        ylabel('Subjects (sorted)')

        title(sprintf( ...
            '%s | %s | Sorted Absolute Latency', ...
            roiName,...
            bandName));

        saveas(fig,...
            fullfile(figDir,...
            sprintf( ...
            '%s_%s_HEATMAP_SORTED.png',...
            roiName,...
            bandName)));

        close(fig)

    end
end

%% =========================================================================
% SUMMARY TABLE
%% =========================================================================

LatencySummary = groupsummary( ...
    LatencyTable,...
    {'ROI','Band'},...
    {'mean','std'},...
    {'NegLatency',...
    'PosLatency',...
    'AbsLatency',...
    'AbsAmp',...
    'MeanDifference',...
    'AUCAbsDifference'});

