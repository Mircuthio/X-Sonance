%% =========================================================================
% STEP4D_TFR_SUBJECT_HEATMAPS_AND_LATENCY
%% =========================================================================
%
% PROJECT
% -------
% X-SONANCE EEG
%
% PURPOSE
% -------
% Subject-level inspection of full-spectrum linear TFR differences.
%
% For every active ROI and frequency band, this script:
%
%   - extracts the subject-level Consonant - Dissonant time course
%   - generates subject-level difference heatmaps
%   - identifies negative, positive and absolute peaks in 0-800 ms
%   - computes descriptive and AUC metrics
%   - saves subject-level and group-summary tables
%
% INPUT
% -----
% STEP4C_TFR_SUBJECT_FULLSPECTRUM_LINEAR_RESULTS.mat
%
% OUTPUTS
% -------
%   LatencyTable
%   LatencySummary
%   Subject-level heatmaps
%
% =========================================================================
clear
close all
clc

origState = get(0,'DefaultFigureVisible');
set(0,'DefaultFigureVisible','off');

set(groot, ...
    'defaultTextInterpreter','tex', ...
    'defaultAxesTickLabelInterpreter','tex', ...
    'defaultLegendInterpreter','tex');

%% =========================================================================
% PATHS
%% =========================================================================
projectRoot = ...
    'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO';

inputFile = fullfile( ...
    projectRoot, ...
    'STEP4B_TFR_MORLET', ...
    'STEP4C_TFR_SUBJECT_FULLSPECTRUM_LINEAR', ...
    'STEP4C_TFR_SUBJECT_FULLSPECTRUM_LINEAR_RESULTS.mat');

outputRoot = fullfile( ...
    projectRoot, ...
    'STEP4B_TFR_MORLET', ...
    'STEP4D_TFR_SUBJECT_HEATMAPS_AND_LATENCY');

if ~exist(outputRoot,'dir')
    mkdir(outputRoot);
end

figDir = fullfile(outputRoot,'Figures');

if ~exist(figDir,'dir')
    mkdir(figDir);
end

%% =========================================================================
% LOAD
%% =========================================================================
load(inputFile,'TFR_Subj','cfgTFR');

subjectNames = fieldnames(TFR_Subj);
nSubjects = numel(subjectNames);

assert(nSubjects > 0, ...
    'No subject-level TFR results were found.');

roiNames = cfgTFR.analysis_rois;

assert(~isempty(roiNames), ...
    'No active ROI found in cfgTFR.analysis_rois.');

bandNames = fieldnames(cfgTFR.freqBands);

analysisTimeWin = [0 0.8];

fprintf('\n=====================================\n');
fprintf('STEP4D HEATMAPS AND LATENCY\n');
fprintf('=====================================\n');
fprintf('Subjects: %d\n',nSubjects);
fprintf('ROIs: %d\n',numel(roiNames));
fprintf('Bands: %d\n',numel(bandNames));
fprintf('Analysis window: %d-%d ms\n', ...
    round(analysisTimeWin(1)*1000), ...
    round(analysisTimeWin(2)*1000));
fprintf('=====================================\n');

%% =========================================================================
% TABLE INITIALIZATION
%% =========================================================================
LatencyTable = table();

%% =========================================================================
% MAIN LOOP
%% =========================================================================
for r = 1:numel(roiNames)

    roiName = roiNames{r};

    fprintf('\n=====================================\n');
    fprintf('ROI: %s\n',roiName);
    fprintf('=====================================\n');

    for b = 1:numel(bandNames)

        bandName = bandNames{b};

        fprintf('Band: %s\n',bandName);

        heatmapData = [];
        timeVector = [];

        negLat = nan(nSubjects,1);
        posLat = nan(nSubjects,1);
        absLat = nan(nSubjects,1);

        negAmp = nan(nSubjects,1);
        posAmp = nan(nSubjects,1);
        absAmp = nan(nSubjects,1);

        aucVal = nan(nSubjects,1);
        meanVal = nan(nSubjects,1);
        stdVal = nan(nSubjects,1);

        %% ================================================================
        % SUBJECT LOOP
        %% ================================================================
        for s = 1:nSubjects

            subjID = subjectNames{s};

            if ~isfield(TFR_Subj.(subjID),roiName)
                warning('%s | %s: ROI missing.', ...
                    subjID, ...
                    roiName);
                continue
            end

            roiData = TFR_Subj.(subjID).(roiName);

            freq = roiData.freq(:);

            bandRange = cfgTFR.freqBands.(bandName);

            idxBand = ...
                freq >= bandRange(1) & ...
                freq <= bandRange(2);

            if ~any(idxBand)
                warning('%s | %s | %s: no frequencies in band.', ...
                    subjID, ...
                    roiName, ...
                    bandName);
                continue
            end

            conTC = mean( ...
                roiData.Consonant.power(idxBand,:), ...
                1, ...
                'omitnan');

            disTC = mean( ...
                roiData.Dissonant.power(idxBand,:), ...
                1, ...
                'omitnan');

            diffTC = conTC - disTC;

            timeVector = roiData.time(:)';

            if isempty(heatmapData)
                heatmapData = nan( ...
                    nSubjects, ...
                    numel(timeVector));
            end

            heatmapData(s,:) = diffTC;

            %% ------------------------------------------------------------
            % PEAKS IN ANALYSIS WINDOW
            %% ------------------------------------------------------------
            idxWin = ...
                timeVector >= analysisTimeWin(1) & ...
                timeVector <= analysisTimeWin(2);

            waveWin = diffTC(idxWin);
            timeWin = timeVector(idxWin);

            if isempty(waveWin)
                warning('%s | %s | %s: empty analysis window.', ...
                    subjID, ...
                    roiName, ...
                    bandName);
                continue
            end

            %% ------------------------------------------------------------
            % NEGATIVE PEAK
            %% ------------------------------------------------------------
            [negAmp(s),idxNeg] = min(waveWin);
            negLat(s) = timeWin(idxNeg);

            %% ------------------------------------------------------------
            % POSITIVE PEAK
            %% ------------------------------------------------------------
            [posAmp(s),idxPos] = max(waveWin);
            posLat(s) = timeWin(idxPos);

            %% ------------------------------------------------------------
            % ABSOLUTE PEAK
            %% ------------------------------------------------------------
            [~,idxAbs] = max(abs(waveWin));
            absLat(s) = timeWin(idxAbs);
            absAmp(s) = waveWin(idxAbs);

            %% ------------------------------------------------------------
            % GLOBAL METRICS
            %% ------------------------------------------------------------
            meanVal(s) = mean(waveWin,'omitnan');
            stdVal(s) = std(waveWin,'omitnan');

            aucVal(s) = trapz( ...
                timeWin, ...
                abs(waveWin));

            %% ------------------------------------------------------------
            % TABLE ROW
            %% ------------------------------------------------------------
            newRow = table( ...
                {roiName}, ...
                {bandName}, ...
                {subjID}, ...
                negAmp(s), ...
                negLat(s), ...
                posAmp(s), ...
                posLat(s), ...
                absAmp(s), ...
                absLat(s), ...
                meanVal(s), ...
                stdVal(s), ...
                aucVal(s), ...
                'VariableNames',{ ...
                'ROI', ...
                'Band', ...
                'Subject', ...
                'NegAmp', ...
                'NegLatency', ...
                'PosAmp', ...
                'PosLatency', ...
                'AbsAmp', ...
                'AbsLatency', ...
                'MeanDifference', ...
                'StdDifference', ...
                'AUCAbsDifference'});

            LatencyTable = [LatencyTable;newRow];
        end

        if isempty(heatmapData)
            warning('%s | %s: no valid subject data.', ...
                roiName, ...
                bandName);
            continue
        end

        %% ================================================================
        % HEATMAP SIMPLE
        %% ================================================================
        fig = figure( ...
            'Color','w', ...
            'Position',[100 100 1200 650]);

        imagesc( ...
            timeVector*1000, ...
            1:nSubjects, ...
            heatmapData, ...
            'Interpolation','bilinear');

        axis xy
        colorbar

        xlabel('Time (ms)')
        ylabel('Subject')

        title(sprintf( ...
            '%s | %s | Consonant - Dissonant', ...
            roiName, ...
            bandName));

        saveas(fig,fullfile(figDir, ...
            sprintf('%s_%s_HEATMAP.png', ...
            roiName, ...
            bandName)));

        close(fig)

        %% ================================================================
        % HEATMAP WITH PEAKS
        %% ================================================================
        fig = figure( ...
            'Color','w', ...
            'Position',[100 100 1200 650]);

        imagesc( ...
            timeVector*1000, ...
            1:nSubjects, ...
            heatmapData, ...
            'Interpolation','bilinear');

        axis xy
        hold on

        validNeg = ~isnan(negLat);
        validPos = ~isnan(posLat);
        validAbs = ~isnan(absLat);

        scatter( ...
            negLat(validNeg)*1000, ...
            find(validNeg), ...
            60, ...
            'wo', ...
            'filled');

        scatter( ...
            posLat(validPos)*1000, ...
            find(validPos), ...
            60, ...
            'gs', ...
            'filled');

        scatter( ...
            absLat(validAbs)*1000, ...
            find(validAbs), ...
            80, ...
            'r*');

        colorbar

        xlabel('Time (ms)')
        ylabel('Subject')

        title(sprintf( ...
            '%s | %s | Peaks', ...
            roiName, ...
            bandName));

        legend( ...
            'Negative Peak', ...
            'Positive Peak', ...
            'Absolute Peak', ...
            'Location','best');

        saveas(fig,fullfile(figDir, ...
            sprintf('%s_%s_HEATMAP_PEAKS.png', ...
            roiName, ...
            bandName)));

        close(fig)

        %% ================================================================
        % HEATMAP SORTED BY ABSOLUTE LATENCY
        %% ================================================================
        [~,ord] = sort(absLat);

        fig = figure( ...
            'Color','w', ...
            'Position',[100 100 1200 650]);

        imagesc( ...
            timeVector*1000, ...
            1:nSubjects, ...
            heatmapData(ord,:), ...
            'Interpolation','bilinear');

        axis xy
        colorbar

        xlabel('Time (ms)')
        ylabel('Subjects (sorted)')

        title(sprintf( ...
            '%s | %s | Sorted Absolute Latency', ...
            roiName, ...
            bandName));

        saveas(fig,fullfile(figDir, ...
            sprintf('%s_%s_HEATMAP_SORTED.png', ...
            roiName, ...
            bandName)));

        close(fig)
    end
end

%% =========================================================================
% SUMMARY TABLE
%% =========================================================================
LatencySummary = groupsummary( ...
    LatencyTable, ...
    {'ROI','Band'}, ...
    {'mean','std'}, ...
    {'NegLatency', ...
    'PosLatency', ...
    'AbsLatency', ...
    'AbsAmp', ...
    'MeanDifference', ...
    'AUCAbsDifference'});

%% =========================================================================
% SAVE
%% =========================================================================
save( ...
    fullfile(outputRoot, ...
    'STEP4D_TFR_SUBJECT_HEATMAPS_AND_LATENCY_RESULTS.mat'), ...
    'LatencyTable', ...
    'LatencySummary', ...
    'cfgTFR', ...
    '-v7.3');

writetable(LatencyTable, ...
    fullfile(outputRoot, ...
    'LatencyTable.csv'));

writetable(LatencySummary, ...
    fullfile(outputRoot, ...
    'LatencySummary.csv'));

fprintf('\n=====================================\n');
fprintf('STEP4D COMPLETED\n');
fprintf('Subject-level rows: %d\n',height(LatencyTable));
fprintf('Summary rows: %d\n',height(LatencySummary));
fprintf('=====================================\n');

set(0,'DefaultFigureVisible',origState);