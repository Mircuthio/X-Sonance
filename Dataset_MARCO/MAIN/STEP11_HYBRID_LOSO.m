subjectIDs = unique( ...
    {FBCSP_Dataset.trials.subjectID});

nSubjects = ...
    numel(subjectIDs);

%% ============================================================
% LOSO
%% ============================================================

Results_LOSO = struct();

for iSub = 1:nSubjects

    testSubject = subjectIDs{iSub};

    fprintf('\n');
    fprintf('================================\n');
    fprintf('LOSO %d/%d\n', ...
        iSub,...
        nSubjects);
    fprintf('TEST SUBJECT: %s\n', ...
        testSubject);
    fprintf('================================\n');

    %% ========================================================
    % ERP SPLIT
    %% ========================================================

    [TrainERP,...
     TestERP] = ...
        split_loso_trials( ...
        ERPINF_Dataset,...
        testSubject);

    %% ========================================================
    % FBCSP SPLIT
    %% ========================================================

    [TrainCSP,...
     TestCSP] = ...
        split_loso_trials( ...
        FBCSP_Dataset,...
        testSubject);

    %% ========================================================
    % FBCSP FEATURES
    %% ========================================================
    nSubEpochs = ...
        max([FBCSP_Dataset.trials.subEpochID]);
    
    FeaturesCSP = ...
        run_fbcsp_features( ...
        TrainCSP,...
        TestCSP,...
        cfgFBCSP);

    [XtrainCSP,Ytrain] = ...
        aggregate_csp_subepochs( ...
        FeaturesCSP.Xtrain,...
        FeaturesCSP.Ytrain,...
        nSubEpochs);

    [XtestCSP,Ytest] = ...
        aggregate_csp_subepochs( ...
        FeaturesCSP.Xtest,...
        FeaturesCSP.Ytest,...
        nSubEpochs);
    %% ========================================================
    % ERP FEATURES
    %% ========================================================

    XtrainERP = ...
        vertcat(TrainERP.ERPINF);

    XtestERP = ...
        vertcat(TestERP.ERPINF);

    %% ========================================================
    % CHECKS
    %% ========================================================

    assert( ...
        size(XtrainERP,1) == size(XtrainCSP,1), ...
        'Training trial mismatch');

    assert( ...
        size(XtestERP,1) == size(XtestCSP,1), ...
        'Test trial mismatch');
    
    %% ========================================================
    % CONTROL
    %% ========================================================
    fprintf('\n');
    fprintf('ERP Train : %d x %d\n', ...
        size(XtrainERP,1), ...
        size(XtrainERP,2));

    fprintf('\n');
    fprintf('ERP FEATURES USED\n');

    disp(ERPINF_Dataset.FeatureNames(:));
    fprintf('CSP Train : %d x %d\n', ...
        size(XtrainCSP,1), ...
        size(XtrainCSP,2));

    fprintf('ERP Test  : %d x %d\n', ...
        size(XtestERP,1), ...
        size(XtestERP,2));

    fprintf('CSP Test  : %d x %d\n', ...
        size(XtestCSP,1), ...
        size(XtestCSP,2));
    %% ========================================================
    % HYBRID FEATURES
    %% ========================================================

    Xtrain = ...
        [XtrainERP XtrainCSP];

    Xtest = ...
        [XtestERP XtestCSP];

    %% ========================================================
    % ZSCORE
    %% ========================================================

    mu = mean(Xtrain,1);

    sd = std(Xtrain,[],1);

    sd(sd==0)=1;

    Xtrain = ...
        (Xtrain-mu)./sd;

    Xtest = ...
        (Xtest-mu)./sd;

    %% ========================================================
    % BUILD HYBRID STRUCTS
    %% ========================================================

    HybridTrain = struct();
    HybridTest = struct();

    for iT = 1:size(Xtrain,1)

        HybridTrain(iT).HYBRID = ...
            Xtrain(iT,:);

        HybridTrain(iT).timeHYBRID = ...
            1:size(Xtrain,2);

        HybridTrain(iT).trialType = ...
            Ytrain(iT);

    end

    for iT = 1:size(Xtest,1)

        HybridTest(iT).HYBRID = ...
            Xtest(iT,:);

        HybridTest(iT).timeHYBRID = ...
            1:size(Xtest,2);

        HybridTest(iT).trialType = ...
            Ytest(iT);

    end

    %% ========================================================
    % CLASSIFIER
    %% ========================================================

    parClassifier = struct();

    parClassifier.InField = ...
        'HYBRID';

    [TrainEEG,...
     TestEEG,...
     outClassifier,...
     PredField,...
     ProbField] = ...
        run_classifier_fold( ...
        HybridTrain,...
        HybridTest,...
        'QDA',...
        parClassifier);

    %% ========================================================
    % PREDICTION
    %% ========================================================

    parPredict = ...
        mdlPredictParams();

    parPredict.InField = ...
        'HYBRID';

    parPredict.OutField = ...
        PredField;

    parPredict.ProbField = ...
        ProbField;

    parPredict.mdl = ...
        outClassifier.mdl;

    [TestEEG,~] = ...
        mdlPredict( ...
        TestEEG,...
        parPredict);

    %% ========================================================
    % METRICS
    %% ========================================================

    Ytrue = ...
        [TestEEG.trialType]';

    Ypred = ...
        [TestEEG.(PredField)]';

    Metrics = ...
        compute_classification_metrics( ...
        Ytrue,...
        Ypred);

    FoldResult = struct();

    FoldResult.testSubject = ...
        testSubject;

    FoldResult.nERPFeatures = ...
        ERPINF_Dataset.nFeatures;

    FoldResult.ERPFeatureNames = ...
        ERPINF_Dataset.FeatureNames;

    FoldResult.nCSPFeatures = ...
        size(XtrainCSP,2);

    FoldResult.nHybridFeatures = ...
        size(Xtrain,2);

    FoldResult.TestMetrics = ...
        Metrics;
    
    FoldResult.nTrainTrials = ...
        size(Xtrain,1);

    FoldResult.nTestTrials = ...
        size(Xtest,1);

    %% RESULT
    Results_LOSO.Fold(iSub) = ...
        FoldResult;
    
end

