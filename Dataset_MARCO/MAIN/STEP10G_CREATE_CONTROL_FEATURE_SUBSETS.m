% STEP10G_CREATE_CONTROL_FEATURE_SUBSETS
%% =========================================================================

clear
close all
clc

%% ============================================================
% PATHS
%% ============================================================

step2_indir = ...
    'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO\';

indir = fullfile( ...
    step2_indir,...
    'STEP10F_CONTROL_DATASETS');

%% ============================================================
% FILES
%% ============================================================

files = dir( ...
    fullfile(indir,...
    '*_FULL.mat'));

fprintf('\n');
fprintf('================================\n');
