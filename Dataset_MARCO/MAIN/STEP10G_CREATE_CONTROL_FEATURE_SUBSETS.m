fprintf('================================\n');
fprintf('Datasets found : %d\n', ...
    numel(files));

%% ============================================================
% LOOP DATASETS
%% ============================================================

for iFile = 1:numel(files)

    fprintf('\n');
    fprintf('--------------------------------\n');
    fprintf('DATASET %d/%d\n', ...
        iFile,...
        numel(files));
    fprintf('%s\n', ...
        files(iFile).name);

    %% ========================================================
    % LOAD
    %% ========================================================

    S = load( ...
        fullfile( ...
        files(iFile).folder,...
        files(iFile).name));

    ERPINF_Dataset = ...
        S.ERPINF_Dataset;

    FeatureNames = ...
        ERPINF_Dataset.FeatureNames;

    %% ========================================================
    % FEATURE MAP
    %% ========================================================

    ERPINDEX_idx = 1:4;

    ERPINDEX_ERANB_idx = ...
        1:10;

    ERPINDEX_MINPEAK_idx = ...
        [1 2 3 4 9 10];

    FULL_idx = ...
        1:numel(FeatureNames);

    %% ========================================================
    % BASENAME
    %% ========================================================

    baseName = ...
        erase( ...
        files(iFile).name,...
        '_FULL.mat');

    %% ========================================================
    % ERPINDEX
    %% ========================================================

    create_subset_dataset( ...
        ERPINF_Dataset,...
        ERPINDEX_idx,...
        fullfile( ...
        indir,...
        sprintf( ...
        '%s_ERPINDEX.mat',...
        baseName)));

    %% ========================================================
    % ERPINDEX + ERANB
    %% ========================================================

    create_subset_dataset( ...
        ERPINF_Dataset,...
        ERPINDEX_ERANB_idx,...
        fullfile( ...
        indir,...
        sprintf( ...
        '%s_ERPINDEX_ERANB.mat',...
        baseName)));

    %% ========================================================
    % ERPINDEX + MINPEAK
    %% ========================================================

    create_subset_dataset( ...
        ERPINF_Dataset,...
        ERPINDEX_MINPEAK_idx,...
        fullfile( ...
        indir,...
        sprintf( ...
        '%s_ERPINDEX_MINPEAK.mat',...
        baseName)));

    %% ========================================================
    % FULL
    %% ========================================================

    create_subset_dataset( ...
        ERPINF_Dataset,...
        FULL_idx,...
        fullfile( ...
        indir,...
        sprintf( ...
        '%s_FULLCOPY.mat',...
        baseName)));

end

fprintf('\n');
fprintf('================================\n');
fprintf('ALL FEATURE SUBSETS CREATED\n');
fprintf('================================\n');

%% =========================================================================
% LOCAL FUNCTION
%% =========================================================================

function create_subset_dataset( ...
    ERPINF_Dataset,...
    keepIdx,...
    saveFile)

DatasetOut = ...
    ERPINF_Dataset;

for iTr = 1:numel(DatasetOut.trials)

    DatasetOut.trials(iTr).ERPINF = ...
        DatasetOut.trials(iTr).ERPINF(keepIdx);

    DatasetOut.trials(iTr).timeERPINF = ...
        1:numel(keepIdx);

end

DatasetOut.FeatureNames = ...
    DatasetOut.FeatureNames(keepIdx);

DatasetOut.nFeatures = ...
    numel(keepIdx);

fprintf('\n');
fprintf('%s\n', ...
    saveFile);

fprintf('Features kept : %d\n', ...
    DatasetOut.nFeatures);

save( ...
    saveFile,...
    'DatasetOut',...
    '-v7.3');

end