%% =========================================================================
% STEP11D_NSA_SUMMARY
%
% GROUP
% +
% SINGLE SUBJECT
%
%% =========================================================================
clear
close all
clc

%% =========================================================================
% PATHS
%% =========================================================================

projectRoot = ...
    'C:\Users\mirco\Desktop\X-SONANCE\Dataset_MARCO';

groupFile = fullfile( ...
    projectRoot,...
    'STEP11B_NSA_MANIFOLD',...
    'NSA_Manifold.mat');

subjectDir = fullfile( ...
    projectRoot,...
    'STEP11C_NSA_SINGLE_SUBJECT');

outdir = fullfile( ...
    projectRoot,...
    'STEP11D_NSA_SUMMARY');

if ~exist(outdir,'dir')
    mkdir(outdir);
end

%% =========================================================================
% GROUP RESULTS
%% =========================================================================

S = load(groupFile);

NSA_Manifold = ...
    S.NSA_Manifold;

GroupTable = ...
    NSA_Manifold.ComponentTable;

fprintf('\n');
fprintf('========================================\n');
fprintf('GROUP RESULTS\n');
fprintf('========================================\n');

disp(GroupTable)

%% =========================================================================
% SUBJECT FILES
%% =========================================================================

subjectFiles = dir( ...
    fullfile( ...
    subjectDir,...
    '**',...
    '*.mat'));

subjectFiles = ...
    subjectFiles(~[subjectFiles.isdir]);

%% =========================================================================
% PREALLOCATE
%% =========================================================================

SubjectSummary = table();

%% =========================================================================
% LOOP SUBJECTS
%% =========================================================================

for iFile = 1:numel(subjectFiles)

    load( ...
        fullfile( ...
        subjectFiles(iFile).folder,...
        subjectFiles(iFile).name));

    subjectName = ...
        erase(subjectFiles(iFile).name,'.mat');

    T = table( ...
        string(subjectName),...
        NSA_SINGLE_SUBJECT.best_component,...
        NSA_SINGLE_SUBJECT.best_time,...
        NSA_SINGLE_SUBJECT.best_pvalue,...
        'VariableNames',{ ...
        'Subject',...
        'BestComponent',...
        'BestTime',...
        'BestPValue'});

    SubjectSummary = ...
        [SubjectSummary ; T];

end

%% =========================================================================
% SORT
%% =========================================================================

SubjectSummary = ...
    sortrows( ...
    SubjectSummary,...
    'BestPValue');

%% =========================================================================
% PRINT
%% =========================================================================

fprintf('\n');
fprintf('========================================\n');
fprintf('SUBJECT SUMMARY\n');
fprintf('========================================\n');

disp(SubjectSummary)

%% =========================================================================
% PCA VARIANCE TABLE
%% =========================================================================

VarianceTable = table();

for iFile = 1:numel(subjectFiles)

    load( ...
        fullfile( ...
        subjectFiles(iFile).folder,...
        subjectFiles(iFile).name));

    explained = ...
        NSA_SINGLE_SUBJECT.explained;

    nKeep = ...
        min(4,length(explained));

    row = table( ...
        string(erase(subjectFiles(iFile).name,'.mat')),...
        explained(1),...
        explained(min(2,end)),...
        explained(min(3,end)),...
        explained(min(4,end)),...
        'VariableNames',{ ...
        'Subject',...
        'PC1',...
        'PC2',...
        'PC3',...
        'PC4'});

    VarianceTable = ...
        [VarianceTable ; row];

end

fprintf('\n');
fprintf('========================================\n');
fprintf('EXPLAINED VARIANCE\n');
fprintf('========================================\n');

disp(VarianceTable)

%% =========================================================================
% SAVE
%% =========================================================================

writetable( ...
    GroupTable,...
    fullfile( ...
    outdir,...
    'NSA_Group_ComponentTable.xlsx'));

writetable( ...
    SubjectSummary,...
    fullfile( ...
    outdir,...
    'NSA_SubjectSummary.xlsx'));

writetable( ...
    VarianceTable,...
    fullfile( ...
    outdir,...
    'NSA_SubjectVariance.xlsx'));

save( ...
    fullfile( ...
    outdir,...
    'NSA_Summary.mat'),...
    'GroupTable',...
    'SubjectSummary',...
    'VarianceTable');

fprintf('\n');
fprintf('========================================\n');
fprintf('STEP11D COMPLETED\n');
fprintf('========================================\n');