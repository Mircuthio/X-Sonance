function [Xagg,Yagg] = ...
    aggregate_csp_subepochs( ...
    Xsub,...
    Ysub,...
    nSubEpochs)

%% ============================================================
% CHECKS
%% ============================================================

assert( ...
    mod(size(Xsub,1),nSubEpochs)==0,...
    'Rows are not divisible by nSubEpochs');

nTrials = ...
    size(Xsub,1) / nSubEpochs;

nFeatures = ...
    size(Xsub,2);

%% ============================================================
% OUTPUT
%% ============================================================

Xagg = zeros( ...
    nTrials,...
    nFeatures*2);

Yagg = zeros( ...
    nTrials,...
    1);

%% ============================================================
% LOOP TRIALS
%% ============================================================

for iTrial = 1:nTrials

    idxStart = ...
        (iTrial-1)*nSubEpochs + 1;

    idxEnd = ...
        iTrial*nSubEpochs;

    Xcurr = ...
        Xsub(idxStart:idxEnd,:);

    %% --------------------------------------------------------
    % MEAN
    %% --------------------------------------------------------

    featMean = ...
        mean(Xcurr,1);

    %% --------------------------------------------------------
    % STD
    %% --------------------------------------------------------

    featStd = ...
        std(Xcurr,[],1);

    %% --------------------------------------------------------
    % HYBRID VECTOR
    %% --------------------------------------------------------

    Xagg(iTrial,:) = ...
        [featMean featStd];

    %% --------------------------------------------------------
    % LABEL
    %% --------------------------------------------------------

    Yagg(iTrial) = ...
        mode(Ysub(idxStart:idxEnd));

end

end